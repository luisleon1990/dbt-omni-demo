        football_name,
        esb_id,
        gsis_it_id,
        smart_id,
        entry_year,
        rookie_year,
        draft_club,
        draft_number
    from {{ source('nflverse', 'roster_2023') }}

    union all

    select
        season,
        team,
        position,
        depth_chart_position,
        jersey_number,
        status,
        full_name,
        first_name,
        last_name,
        birth_date,
